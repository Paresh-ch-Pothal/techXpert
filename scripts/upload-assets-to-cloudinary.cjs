/**
 * One-time migration script.
 * Uploads the logos/backgrounds/video/certificate-template sitting in
 * /assets-for-cloudinary into your Cloudinary account, then rewrites
 * client/src/config/media.js with the resulting secure URLs.
 *
 * USAGE:
 *   1. cd server && npm install        (cloudinary is already a server dependency)
 *   2. Make sure server/.env has CLOUD_NAME, API_KEY, API_SECRET
 *   3. From the project root run:
 *        node scripts/upload-assets-to-cloudinary.cjs
 *   4. Once it prints "Done", delete the /assets-for-cloudinary folder —
 *      you no longer need the local copies, everything now loads from Cloudinary.
 */

const path = require("path");
const fs = require("fs");
const cloudinary = require(path.join(__dirname, "../server/node_modules/cloudinary")).v2;
require(path.join(__dirname, "../server/node_modules/dotenv")).config({
  path: path.join(__dirname, "../server/.env"),
});

cloudinary.config({
  cloud_name: process.env.CLOUD_NAME,
  api_key: process.env.API_KEY,
  api_secret: process.env.API_SECRET,
});

const SOURCE_DIR = path.join(__dirname, "../assets-for-cloudinary");
const MEDIA_CONFIG_PATH = path.join(__dirname, "../client/src/config/media.js");

// filename -> [key in media.js, resource_type]
const ASSET_MAP = {
  "logoHome.png": ["logoHome", "image"],
  "logoNav.png": ["logoNav", "image"],
  "logoclass.png": ["logoClass", "image"],
  "logofoot.png": ["logoFoot", "image"],
  "back1.png": ["back1", "image"],
  "back2.png": ["back2", "image"],
  "back3.png": ["back3", "image"],
  "certificate.jpg": ["certificateTemplate", "image"],
  "video1.mp4": ["video1", "video"],
};

async function main() {
  if (!process.env.CLOUD_NAME || !process.env.API_KEY || !process.env.API_SECRET) {
    console.error("Missing CLOUD_NAME / API_KEY / API_SECRET. Add them to server/.env first.");
    process.exit(1);
  }

  const results = {};

  for (const [filename, [key, resourceType]] of Object.entries(ASSET_MAP)) {
    const filePath = path.join(SOURCE_DIR, filename);
    if (!fs.existsSync(filePath)) {
      console.warn(`Skipping ${filename} - not found in assets-for-cloudinary/`);
      continue;
    }
    console.log(`Uploading ${filename}...`);
    const uploadResult = await cloudinary.uploader.upload(filePath, {
      folder: "techxpert-static",
      resource_type: resourceType,
      public_id: path.parse(filename).name,
      overwrite: true,
    });
    results[key] = uploadResult.secure_url;
    console.log(`  -> ${uploadResult.secure_url}`);
  }

  const fileContent = `// Auto-generated by scripts/upload-assets-to-cloudinary.cjs on ${new Date().toISOString()}
export const media = {
${Object.entries(results)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n")}
};
`;

  fs.writeFileSync(MEDIA_CONFIG_PATH, fileContent);
  console.log(`\nDone. Wrote ${Object.keys(results).length} URLs to client/src/config/media.js`);
  console.log("You can now delete the /assets-for-cloudinary folder.");
}

main().catch((err) => {
  console.error("Upload failed:", err);
  process.exit(1);
});
